package com.example

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import com.example.auth.GoogleSignInManager
import com.example.data.AppRepository
import com.example.ui.OceanSurferViewModel
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class GoogleSignInTest {

  @Test
  fun defaultWebClientId_isGeneratedFromGoogleServicesJson() {
    val context = ApplicationProvider.getApplicationContext<Context>()
    val webClientId = GoogleSignInManager.resolveWebClientId(context)
    assertNotNull("R.string.default_web_client_id must be generated by Google Services plugin", webClientId)
    assertTrue(webClientId!!.endsWith(".apps.googleusercontent.com"))
  }

  @Test
  fun googleAuthState_handlesCancelErrorClearAndSignOutCleanly() {
    val context = ApplicationProvider.getApplicationContext<Context>()
    val app = context.applicationContext as OceanSurferApp
    val vm = OceanSurferViewModel(AppRepository(app.database), context)

    assertFalse(vm.googleAccountState.value.isSignedIn)

    vm.onGoogleAuthLoading(true)
    assertTrue(vm.googleAccountState.value.isLoading)
    assertNull(vm.googleAccountState.value.errorMessage)

    vm.onGoogleAuthCancelled()
    assertFalse(vm.googleAccountState.value.isLoading)
    assertNotNull(vm.googleAccountState.value.errorMessage)
    assertTrue(vm.googleAccountState.value.errorMessage!!.contains("cancelled", ignoreCase = true))

    vm.clearGoogleAuthError()
    assertNull(vm.googleAccountState.value.errorMessage)

    vm.onGoogleAuthError("No Google Account found on this device.")
    assertFalse(vm.googleAccountState.value.isLoading)
    assertEquals("No Google Account found on this device.", vm.googleAccountState.value.errorMessage)

    vm.onGoogleSignedOut()
    assertFalse(vm.googleAccountState.value.isSignedIn)
    assertNull(vm.googleAccountState.value.errorMessage)
  }
}
